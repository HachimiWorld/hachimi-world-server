#!/bin/sh
# Posts the API changes of the open PR for this branch, against the PR's base branch, as one PR
# comment that later pushes update. Runs in the oasdiff image (Alpine) with GITHUB_TOKEN set;
# DRY_RUN=1 prints the comment instead.
set -eu

marker='<!-- oasdiff-api-changelog -->'
api="https://api.github.com/repos/$CI_REPO"

gh() {
  curl -fsS -H "User-Agent: hachimi-world-ci" -H "Authorization: Bearer $GITHUB_TOKEN" -H "Accept: application/vnd.github+json" "$@"
}

pr_json=$(gh "$api/pulls?state=open&head=$CI_REPO_OWNER:$CI_COMMIT_BRANCH")
pr=$(printf '%s' "$pr_json" | jq -r '.[0].number // empty')
if [ -z "$pr" ]; then
  echo "No open PR for $CI_COMMIT_BRANCH, nothing to comment on"
  exit 0
fi
base=$(printf '%s' "$pr_json" | jq -r '.[0].base.ref')

git fetch --depth=1 origin "$base"
{
  echo "$marker"
  echo "### API changes against \`$base\`"
  echo
  echo "At ${CI_COMMIT_SHA}. Generated by \`oasdiff changelog\` from \`openapi.json\`; only modules on \`ApiRouter\` are covered."
  echo
  if git cat-file -e FETCH_HEAD:openapi.json 2>/dev/null; then
    git show FETCH_HEAD:openapi.json > /tmp/openapi-base.json
    # Drop oasdiff's own title line; the heading above names the base
    oasdiff changelog /tmp/openapi-base.json openapi.json --format markdown \
      --severity-levels .oasdiff-severity-levels --err-ignore .oasdiff-err-ignore | sed '1{/^# API Changelog/d}'
  else
    echo "\`$base\` has no \`openapi.json\` yet, so there's nothing to compare."
  fi
} > /tmp/comment.md

if [ -n "${DRY_RUN:-}" ]; then
  echo "Would comment on #$pr:"
  cat /tmp/comment.md
  exit 0
fi

body=$(jq -Rs '{body: .}' < /tmp/comment.md)
existing=$(gh "$api/issues/$pr/comments?per_page=100" | jq -r --arg m "$marker" '[.[] | select(.body | startswith($m))][0].id // empty')
if [ -n "$existing" ]; then
  gh -X PATCH "$api/issues/comments/$existing" -d "$body" > /dev/null
  echo "Updated the API changelog comment on #$pr"
else
  gh -X POST "$api/issues/$pr/comments" -d "$body" > /dev/null
  echo "Posted the API changelog comment on #$pr"
fi
