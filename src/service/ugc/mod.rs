//! The kinds of user-generated content that can be reported, and what a decision can do to each.
//!
//! The report flow is the same for every kind; the steps that touch the content are left to the
//! kind's adapter (`song.rs`, `playlist.rs`, `user.rs`, `comment.rs`): who owns the target and who
//! can see it, how it looks ([UgcPreview]), which content actions it offers and how to take them,
//! what to refresh afterwards, and what to tell its owner.
//! An adapter knows its own content and nothing else, and declares its own actions.
//!
//! Each adapter implements [UgcAdapter], and each [UgcKind] variant carries its adapter; the
//! forwarding from the enum to the adapters is generated by `enum_dispatch`, so nothing here
//! matches on the kind by hand. Previews work the same way: each kind defines its own preview
//! struct and implements [Preview] for it, and [UgcPreview] only lists them. Adding a kind means a
//! new adapter and preview, and a variant for each; [UgcKind::iter] finds the new kind by itself,
//! and the compiler points at any method left out.
use crate::db::user::UserId;

mod comment;
mod playlist;
mod song;
mod user;

pub(crate) use song::preview as song_preview;
pub use comment::CommentPreview;
pub use playlist::PlaylistPreview;
pub use song::SongPreview;
pub use user::UserPreview;

use crate::service::notification::ContentIntent;
use crate::web::state::AppState;
use enum_dispatch::enum_dispatch;
use serde::{Deserialize, Serialize};
use sqlx::{PgPool, PgTransaction};
use strum::{EnumIter, IntoEnumIterator};

/// A reportable kind. Each variant carries the kind's adapter, and [enum_dispatch] implements
/// [UgcAdapter] for the enum by forwarding to it, so calling a method on a kind runs that kind's
/// adapter without a hand-written match. [EnumIter] lists every kind, with each adapter made by
/// [Default].
#[enum_dispatch(UgcAdapter)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, EnumIter)]
pub enum UgcKind {
    Song(song::SongAdapter),
    Playlist(playlist::PlaylistAdapter),
    User(user::UserAdapter),
    Comment(comment::CommentAdapter),
}

/// A target in the shape the report flow needs, whatever its kind: used to check who may report
/// it and what a decision can do, shown in the report queue, and kept as a snapshot with each
/// action. The flow reads the owner and visibility; the preview is the kind's own business.
/// @since 261008
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UgcTarget {
    pub owner_uid: UserId,
    /// Whether people other than the owner can see it.
    pub is_public: bool,
    /// Hidden by the platform.
    /// @since 261008
    #[serde(default)]
    pub is_hidden: bool,
    /// @since 261021
    pub preview: UgcPreview,
}

/// How a target looks, in the shape of its kind, with `type` naming the kind. Each variant carries
/// the preview its kind's file defines; [enum_dispatch] implements [Preview] for the enum by
/// forwarding to it, as [UgcKind] does for adapters.
/// @since 261021
#[enum_dispatch(Preview)]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum UgcPreview {
    Song(SongPreview),
    Playlist(PlaylistPreview),
    User(UserPreview),
    Comment(CommentPreview),
}

/// What every preview provides beyond its own fields. Implemented once per kind, next to its
/// adapter.
#[enum_dispatch]
pub trait Preview {
    /// The main line: a song's title, a playlist's name, a username or a comment's text.
    fn headline(&self) -> &str;

    /// The flat fields report clients read before 261021, until they read the preview.
    fn legacy_card(&self) -> LegacyCard;
}

/// The report target fields clients read before 261021.
#[derive(Debug, Clone, Default)]
pub struct LegacyCard {
    pub title: String,
    pub cover_url: Option<String>,
    /// A song's display id, also for a comment on a song; empty otherwise.
    pub display_id: String,
}

/// Something a decision can do to the content, declared by the kind's adapter. The report flow
/// only knows its id and whether it is a penalty.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ContentAction {
    /// Stable id used in the API and stored with the decision, such as `hide`.
    pub id: &'static str,
    /// Acts against the content: it goes with an upheld report, and the owner must be told why.
    /// Otherwise it undoes an earlier penalty and goes with a rejected one.
    pub penalty: bool,
}

/// What to tell the owner about a decision on their content.
pub struct OwnerMessage {
    pub notification_type: &'static str,
    pub title: &'static str,
    pub body: String,
    pub intent: ContentIntent,
}

/// What every reportable kind provides. Implemented once per kind, in its own file; a kind that
/// leaves a method out doesn't compile.
// Only called through the concrete UgcKind, so the futures' auto traits (Send) are known
#[allow(async_fn_in_trait)]
#[enum_dispatch]
pub trait UgcAdapter {
    /// The kind's name in the API and in storage, such as `song`.
    fn name(&self) -> &'static str;

    /// Every content action the kind declares, for reading past decisions.
    fn actions(&self) -> &'static [ContentAction];

    /// Reads the target from its own table and describes it as a [UgcTarget]. None if it doesn't
    /// exist.
    async fn load(&self, pool: &PgPool, id: i64) -> sqlx::Result<Option<UgcTarget>>;

    /// Content actions a decision can take on `target` now.
    fn content_actions(&self, target: &UgcTarget) -> Vec<ContentAction>;

    /// Takes `actions`, already checked against [Self::content_actions], in the decision's
    /// transaction.
    async fn apply(&self, tx: &mut PgTransaction<'_>, id: i64, actions: &[ContentAction]) -> anyhow::Result<()>;

    /// Refreshes caches and the search index after a decision that took content actions commits.
    /// Failures are logged.
    async fn refresh(&self, state: &AppState, id: i64);

    /// How the target is named in user-facing text, such as 作品《X》, or just 作品 if it's gone.
    fn mention(&self, target: Option<&UgcTarget>) -> String;

    /// Tells the owner what `actions` did to their content. None if they did nothing.
    /// `reason_suffix` is appended to the body as is.
    fn owner_message(&self, id: i64, target: &UgcTarget, actions: &[ContentAction], reason_suffix: &str) -> Option<OwnerMessage>;
}

impl UgcKind {
    pub fn parse(s: &str) -> Option<Self> {
        Self::iter().find(|x| x.name() == s)
    }

    pub fn as_str(self) -> &'static str {
        self.name()
    }
}

#[cfg(test)]
mod tests {
    use super::{CommentPreview, SongPreview, UgcKind, UgcPreview};
    use serde_json::json;
    use strum::IntoEnumIterator;

    #[test]
    fn previews_are_tagged_by_kind() {
        let song = SongPreview { title: "T".into(), cover_url: "c".into(), display_id: "JM-AAAA-001".into() };
        let preview = UgcPreview::Comment(CommentPreview { content: "Nice".into(), on: Some(Box::new(UgcPreview::Song(song))) });
        let value = serde_json::to_value(&preview).unwrap();
        assert_eq!(value, json!({
            "type": "comment",
            "content": "Nice",
            "on": { "type": "song", "title": "T", "cover_url": "c", "display_id": "JM-AAAA-001" },
        }));
        assert_eq!(serde_json::from_value::<UgcPreview>(value).unwrap(), preview);
    }

    #[test]
    fn every_kind_parses_back() {
        let kinds: Vec<UgcKind> = UgcKind::iter().collect();
        assert_eq!(kinds.len(), 4);
        for kind in kinds {
            assert_eq!(UgcKind::parse(kind.as_str()), Some(kind));
        }
    }
}
